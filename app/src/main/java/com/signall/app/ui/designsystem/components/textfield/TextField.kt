@Immutable
object TextFieldDefaults {
    val MinHeight = TextFieldMinHeight
    val Shape: Shape = RoundedCornerShape(8.dp)

    private fun contentPadding(
        start: Dp = TextFieldHorizontalPadding,
        end: Dp = TextFieldHorizontalPadding,
        top: Dp = TextFieldVerticalPadding,
        bottom: Dp = TextFieldVerticalPadding,
    ): PaddingValues = PaddingValues(start, top, end, bottom)

    private fun labelPadding(
        start: Dp = 0.dp,
        top: Dp = 0.dp,
        end: Dp = 0.dp,
        bottom: Dp = LabelBottomPadding,
    ): PaddingValues = PaddingValues(start, top, end, bottom)

    private fun supportingTextPadding(
        start: Dp = 0.dp,
        top: Dp = SupportingTopPadding,
        end: Dp = TextFieldHorizontalPadding,
        bottom: Dp = 0.dp,
    ): PaddingValues = PaddingValues(start, top, end, bottom)

    @Composable
    private fun leadingIconPadding(
        start: Dp = HorizontalIconPadding,
        top: Dp = 0.dp,
        end: Dp = 0.dp,
        bottom: Dp = 0.dp,
    ): PaddingValues = PaddingValues(start, top, end, bottom)

    @Composable
    private fun trailingIconPadding(
        start: Dp = 0.dp,
        top: Dp = 0.dp,
        end: Dp = HorizontalIconPadding,
        bottom: Dp = 0.dp,
    ): PaddingValues = PaddingValues(start, top, end, bottom)

    @Composable
    fun containerBorderThickness(
        interactionSource: InteractionSource,
    ): Dp {
        val focused by interactionSource.collectIsFocusedAsState()

        return if (focused) FocusedOutlineThickness else UnfocusedOutlineThickness
    }

    @Composable
    fun DecorationBox(
        value: String,
        innerTextField: @Composable () -> Unit,
        enabled: Boolean,
        visualTransformation: VisualTransformation,
        interactionSource: InteractionSource,
        isError: Boolean = false,
        label: @Composable (() -> Unit)? = null,
        placeholder: @Composable (() -> Unit)? = null,
        leadingIcon: @Composable (() -> Unit)? = null,
        trailingIcon: @Composable (() -> Unit)? = null,
        prefix: @Composable (() -> Unit)? = null,
        suffix: @Composable (() -> Unit)? = null,
        supportingText: @Composable (() -> Unit)? = null,
        shape: Shape = Shape,
        colors: TextFieldColors = colors(),
        container: @Composable () -> Unit = {
            ContainerBox(enabled, isError, interactionSource, colors, shape)
        },
    ) {
        CommonDecorationBox(
            value = value,
            innerTextField = innerTextField,
            visualTransformation = visualTransformation,
            placeholder = placeholder,
            label = label,
            leadingIcon = leadingIcon,
            trailingIcon = trailingIcon,
            prefix = prefix,
            suffix = suffix,
            supportingText = supportingText,
            enabled = enabled,
            isError = isError,
            interactionSource = interactionSource,
            colors = colors,
            contentPadding = contentPadding(),
            labelPadding = labelPadding(),
            supportingTextPadding = supportingTextPadding(),
            leadingIconPadding = leadingIconPadding(),
            trailingIconPadding = trailingIconPadding(),
            container = container,
        )
    }

    @Composable
    fun ContainerBox(
        enabled: Boolean,
        isError: Boolean,
        interactionSource: InteractionSource,
        colors: TextFieldColors,
        shape: Shape = Shape,
        borderThickness: Dp = containerBorderThickness(interactionSource),
    ) {
        Box(
            Modifier
                .background(colors.containerColor(enabled, isError, interactionSource).value, shape)
                .containerOutline(enabled, isError, interactionSource, colors, borderThickness, shape),
        )
    }

    @Composable
    fun colors(): TextFieldColors {
        return TextFieldColors(
            focusedTextColor = SignAllTheme.colors.text,
            unfocusedTextColor = SignAllTheme.colors.text,
            disabledTextColor = SignAllTheme.colors.onDisabled,
            errorTextColor = SignAllTheme.colors.text,
            focusedContainerColor = SignAllTheme.colors.surface,
            unfocusedContainerColor = SignAllTheme.colors.surface,
            disabledContainerColor = SignAllTheme.colors.disabled,
            errorContainerColor = SignAllTheme.colors.surface,
            cursorColor = SignAllTheme.colors.primary,
            errorCursorColor = SignAllTheme.colors.error,
            textSelectionColors = LocalTextSelectionColors.current,
            focusedOutlineColor = SignAllTheme.colors.transparent,
            unfocusedOutlineColor = SignAllTheme.colors.transparent,
            disabledOutlineColor = SignAllTheme.colors.transparent,
            errorOutlineColor = SignAllTheme.colors.error,
            focusedLeadingIconColor = SignAllTheme.colors.primary,
            unfocusedLeadingIconColor = SignAllTheme.colors.primary,
            disabledLeadingIconColor = SignAllTheme.colors.onDisabled,
            errorLeadingIconColor = SignAllTheme.colors.primary,
            focusedTrailingIconColor = SignAllTheme.colors.primary,
            unfocusedTrailingIconColor = SignAllTheme.colors.primary,
            disabledTrailingIconColor = SignAllTheme.colors.onDisabled,
            errorTrailingIconColor = SignAllTheme.colors.primary,
            focusedLabelColor = SignAllTheme.colors.primary,
            unfocusedLabelColor = SignAllTheme.colors.primary,
            disabledLabelColor = SignAllTheme.colors.textDisabled,
            errorLabelColor = SignAllTheme.colors.error,
            focusedPlaceholderColor = SignAllTheme.colors.textSecondary,
            unfocusedPlaceholderColor = SignAllTheme.colors.textSecondary,
            disabledPlaceholderColor = SignAllTheme.colors.textDisabled,
            errorPlaceholderColor = SignAllTheme.colors.textSecondary,
            focusedSupportingTextColor = SignAllTheme.colors.primary,
            unfocusedSupportingTextColor = SignAllTheme.colors.primary,
            disabledSupportingTextColor = SignAllTheme.colors.textDisabled,
            errorSupportingTextColor = SignAllTheme.colors.error,
            focusedPrefixColor = SignAllTheme.colors.primary,
            unfocusedPrefixColor = SignAllTheme.colors.primary,
            disabledPrefixColor = SignAllTheme.colors.onDisabled,
            errorPrefixColor = SignAllTheme.colors.primary,
            focusedSuffixColor = SignAllTheme.colors.primary,
            unfocusedSuffixColor = SignAllTheme.colors.primary,
            disabledSuffixColor = SignAllTheme.colors.onDisabled,
            errorSuffixColor = SignAllTheme.colors.primary,
        )
    }
}
