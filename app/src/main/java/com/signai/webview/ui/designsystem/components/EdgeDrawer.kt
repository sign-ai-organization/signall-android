// CUSTOMIZED — not generated by `lumo --add` (Lumo has no side drawer).
//
// ┌──────────────────────────────────────────────────────────────────────────┐
// │ ORO / GOTCHA: Compose hit-testing vs. embedded Android Views vs. disabled │
// │ gestures. Read this before touching the drawer layering (spec `EDG-22`).  │
// │                                                                          │
// │ Two traps made tap-outside-to-close and the left tab dead for weeks:      │
// │                                                                          │
// │ 1) A `draggable`/`clickable` with `enabled = false` STILL registers a     │
// │    pointer-input node, and that node remains the topmost hit route in     │
// │    Compose. Sibling drawers are stacked full-screen, so the inactive      │
// │    drawer's edge strip/handle silently swallowed every tap meant for the  │
// │    active drawer's backdrop. Fix: DO NOT attach the gesture at all when   │
// │    it may not act (`.then(if (enabled) Modifier.draggable(...) else       │
// │    Modifier)`). A plain layout node without pointer input is skipped by   │
// │    hit-testing, so it can still be drawn (for a fade) without blocking.   │
// │                                                                          │
// │ 2) An WebView/`AndroidView` is a real child View: it takes every touch    │
// │    inside its bounds and no Compose sibling paints over it. It must be    │
// │    the FIRST (bottom) child, drawers on top of it, and its               │
// │    `pointerInteropFilter` returns true while a drawer is open so the      │
// │    scene never eats the panel/backdrop gestures.                         │
// │                                                                          │
// │ Also: the backdrop must be full-screen, composed BEFORE the panel and     │
// │ the handle (so they keep their own touches) and AFTER the drawer above    │
// │ it is excluded. Only ONE drawer may compose interactive overlays.         │
// └──────────────────────────────────────────────────────────────────────────┘
//
// Generalized to BOTH sides (spec `EDG-13`): `side = DrawerSide.Start` (left,
// Conversación) or `DrawerSide.End` (right, Ajustes). One gesture model:
//
// - OPEN: an invisible edge strip on the drawer's half of the screen is
//   draggable, plus a visible grab tab (handle) that can be tapped or dragged.
// - CLOSE: drag the body/handle toward the edge, tap the scrim, or press back.
// - PREVIEW: while dragging, a translucent panel with the drawer label follows
//   the finger (spec `EDG-6`).
//
// Drive model: a single signed `Animatable<Float>` `offsetX` (px). Closed is at
// `direction * widthPx` (direction = +1 End / -1 Start), open is 0. Deltas are
// always `offsetX + delta` because opening is leftward on End and rightward on
// Start (Compose reports positive deltas for rightward finger movement).

enum class DrawerSide { Start, End }

// Velocidad (dp/s) a partir de la cual un arrastre decide por sí solo: abre o
// cierra completo aunque el dedo haya recorrido poco. Es el `velocityThreshold`
// del drawer modal de Material 3 (`SwipeableDefaults`, 125 dp/s) y es lo que
// hace que un pestañeo abra el panel, como en Gmail o en X/Twitter. Por debajo
// del umbral decide la distancia (la mitad del panel). Valores medidos con
// gestos reales de 1-2 frames quedan muy por encima; un arrastre lento y
// deliberado queda por debajo.
private val DrawerFlingVelocity = 125.dp

@Composable
fun SignAiEdgeDrawer(
    side: DrawerSide,
    isOpen: Boolean,
    onOpenChange: (Boolean) -> Unit,
    modifier: Modifier = Modifier,
    drawerWidth: Dp = SignAiSizes.drawerWidth,
    // Zona de arrastre invisible en el borde. Subió de 48 a 60 dp (+25 %) el
    // 2026-10-22 porque con navegación por gestos el sistema se queda con los
    // primeros ~20 dp de cada lado; ver [handleHitPadding].
    edgeStripWidth: Dp = 60.dp,
    // Grab strip of the OPEN drawer: wider than the closed-side strip, since
    // this one is an actual drag handle and not just a screen-edge swipe zone.
    handleDragWidth: Dp = 90.dp,
    // ZONA TÁCTIL INVISIBLE de la pestaña, extra **hacia adentro de la pantalla**.
    //
    // El dibujo del tab son 20dp pegados al borde, y MIUI se come los primeros ~15dp
    // de cada lado con sus gestos de sistema: del ancho útil quedaban muy poco y en el
    // Redmi Note 9S el owner no lograba abrir los paneles (2026-10-16). Esto suma ancho
    // solo al nodo que recibe el toque — el tab sigue siendo 20x62dp, con la misma
    // sombra y el mismo grip, y `contentAlignment` lo mantiene pegado al borde porque el
    // Box crece hacia el interior. Es el mismo truco que en un iPhone: la Diana es chica
    // a la vista y grande al dedo.
    //
    // Subió de 28 a 35 dp (+25 %) el 2026-10-22, junto con el alto del nodo (160 → 200
    // dp) y con `systemGestureExclusion` (ver abajo): el owner usa navegación por gestos
    // y el gesto de "atrás" del sistema se quedaba con el arrastre desde el borde.
    handleHitPadding: Dp = 35.dp,
    edgeStripBottomExclusion: Dp = 0.dp,
    previewLabel: String = "",
    // The other drawer is the one on screen. The open gestures (edge strip and
    // handle drag) are inert while it is: with a drawer open the only way out is
    // closing it (tap its backdrop/handle, drag it back, or press back), so the
    // two drawers can never cross-fade into each other (spec `EDG-19`).
    otherDrawerOpen: Boolean = false,
    // This drawer's own open fraction (0 closed → 1 open), echoed back by the
    // host. The handle of the drawer that IS open uses it to take its dim as the
    // backdrop fades in, so the closed side never flashes undimmed (spec
    // `EDG-14`).
    currentlyOpenFraction: Float = 0f,
    // Open fraction of the OTHER drawer (0 closed → 1 open). This tab fades out
    // in step with the counterpart opening, instead of switching off only when
    // the counterpart is fully open (spec `EDG-19`/`EDG-22`).
    otherOpenFraction: Float = 0f,
    // Reports this drawer's open fraction (0 closed → 1 open) so its own handle
    // can follow the same backdrop animation.
    onFractionChange: (Float) -> Unit = {},
    // Synchronous, host-owned lock so two fingers cannot start a gesture on both
    // tabs at once (spec `EDG-19`). `claimGesture` is called on the very first
    // pointer event and must answer immediately, before recomposition; it
    // returns false when the other side already owns the gesture.
    claimGesture: () -> Boolean = { true },
    releaseGesture: () -> Unit = {},
    drawerContent: @Composable () -> Unit,
    content: @Composable () -> Unit,
) {
    val density = LocalDensity.current
    val widthPx = with(density) { drawerWidth.toPx() }
    val edgeStripWidthPx = with(density) { edgeStripWidth.toPx() }
    val flingVelocityPx = with(density) { DrawerFlingVelocity.toPx() }
    val scope = rememberCoroutineScope()

    // 1 while this tab is fully visible, 0 while it has faded out because the
    // other drawer is taking over. It follows the counterpart's open fraction
    // (which is itself animated by its `Animatable`), so the fade is exactly in
    // step with the other drawer sliding in — it starts the moment the gesture
    // (or the tap's opening animation) begins, not when it finishes.
    val enabledFraction =
        if (isOpen) 1f else (1f - otherOpenFraction.coerceIn(0f, 1f))

    val direction = if (side == DrawerSide.End) 1f else -1f
    val closedOffset = direction * widthPx
    val minOffset = if (side == DrawerSide.End) 0f else -widthPx
    val maxOffset = if (side == DrawerSide.End) widthPx else 0f

    val offsetX = remember(side) { Animatable(if (isOpen) 0f else closedOffset) }
    var dragging by remember { mutableStateOf(false) }
    // Whether the in-flight gesture owns the host lock; only then does it move.
    var gestureOwned by remember { mutableStateOf(false) }
    val reduceMotion = LocalReduceMotion.current

    // SIN REBOTE (owner, 2026-11-03). El spring anterior era
    // `DampingRatioMediumBouncy` (ζ = 0,5), cuyo sobrepaso máximo es
    // `e^(-πζ/√(1-ζ²))` = 16,3 % del recorrido: unos 49 dp sobre un panel de
    // 300 dp. El panel se pasaba del borde de la pantalla, dejaba ver el fondo
    // y volvía, y por eso existía la franja `drawerOverflow` de 64 dp fuera de
    // cuadro que tapaba ese hueco. Con ζ = 1 (crítico) el panel llega, se
    // asienta y se queda quieto, sin sobrepaso y sin franja.
    //
    // La rigidez se deja igual a propósito: el spring es una propiedad del
    // recorrido, así que la velocidad se siente igual que antes y el cambio
    // vale para cualquier ancho de panel (`panelWidth = min(maxWidth * 0.88,
    // 350.dp)`) y cualquier densidad, sin un dp fijo que pueda quedar corto.
    LaunchedEffect(isOpen) {
        if (!dragging) {
            val target = if (isOpen) 0f else closedOffset
            if (reduceMotion) {
                offsetX.snapTo(target)
            } else {
                offsetX.animateTo(
                    targetValue = target,
                    animationSpec = spring(
                        dampingRatio = Spring.DampingRatioNoBouncy,
                        stiffness = Spring.StiffnessMedium,
                    ),
                )
            }
        }
    }

    val fraction = (1f - abs(offsetX.value) / widthPx).coerceIn(0f, 1f)

    LaunchedEffect(fraction) { onFractionChange(fraction) }

    val dragState = rememberDraggableState { delta ->
        if (gestureOwned) {
            scope.launch {
                offsetX.snapTo((offsetX.value + delta).coerceIn(minOffset, maxOffset))
            }
        }
    }
    val startDrag: () -> Unit = {
        gestureOwned = claimGesture()
        dragging = gestureOwned
    }
    val snapAfterDrag: (Float) -> Unit = { velocity ->
        dragging = false
        gestureOwned = false
        releaseGesture()
        // Cómo decide un drawer estándar (DrawerLayout de Gmail, Material 3):
        // primero la VELOCIDAD del gesto, y solo si no hubo fling, la distancia.
        // Antes acá se miraba únicamente la mitad del recorrido, así que un
        // pestañeo rápido se ignoraba y el panel se devolvía (owner, 2026-11-03).
        //
        // `velocity` llega en px/s con el signo del dedo: positivo = el dedo va
        // hacia la derecha. `offsetX` crece hacia la derecha, así que el signo se
        // usa tal cual, sin invertirlo por lado.
        val towardOpen = if (side == DrawerSide.End) velocity < 0f else velocity > 0f
        val towardClosed = if (side == DrawerSide.End) velocity > 0f else velocity < 0f
        val passedHalfway = abs(offsetX.value) < widthPx / 2f
        // A drawer cannot be dragged open while the other one is on screen.
        val shouldOpen =
            !otherDrawerOpen &&
                when {
                    abs(velocity) < flingVelocityPx -> passedHalfway
                    towardOpen -> true
                    towardClosed -> false
                    else -> passedHalfway
                }
        val target = if (shouldOpen) 0f else closedOffset
        // La velocidad se arrastra al resorte SOLO si empuja hacia el destino.
        // En contra del destino, un resorte crítico igual podría pasarse del
        // borde, que es justo lo que se está quitando (ver el comentario de
        // `LaunchedEffect(isOpen)`). Con la misma dirección el recorrido es
        // monótono: llega y se queda.
        val towardTarget = if (shouldOpen) towardOpen else towardClosed
        val carriedVelocity = if (towardTarget) velocity else 0f
        scope.launch {
            if (reduceMotion) {
                offsetX.snapTo(target)
            } else {
                // Mismo criterio que la apertura por tap: ζ = 1. Sobre
                // `StiffnessHigh` el tramo que falta recorrer se hace en muy
                // pocos frames, así que soltar el arrastre sigue sintiéndose
                // inmediato, y ahora además hereda el impulso del dedo en vez de
                // arrancar de cero.
                offsetX.animateTo(
                    targetValue = target,
                    animationSpec = spring(
                        dampingRatio = Spring.DampingRatioNoBouncy,
                        stiffness = Spring.StiffnessHigh,
                    ),
                    initialVelocity = carriedVelocity,
                )
            }
            onOpenChange(shouldOpen)
        }
    }

    val horizontalAlignment = if (side == DrawerSide.End) Alignment.CenterEnd else Alignment.CenterStart
    val topAlignment = if (side == DrawerSide.End) Alignment.TopEnd else Alignment.TopStart
    val drawerShape =
        if (side == DrawerSide.End) SignAiShapes.cornerDrawerRight
        else SignAiShapes.cornerDrawerLeft

    BoxWithConstraints(modifier = modifier.fillMaxSize()) {
        content()

        // Prototype `.edge-tab { top: 42% }`: the tab's top sits at 42% of the
        // screen height, i.e. slightly above the vertical center. The handle Box
        // is 160dp tall and centered, so shift it up by 8% of the height (plus
        // the half-tab correction to align the 62dp tab's top).
        val tabOffsetY = 31.dp - maxHeight * 0.08f

        // Invisible gesture strip on this drawer's edge. `padding` BEFORE
        // `fillMaxHeight` shrinks the node itself, so the hit area excludes the
        // bottom bar instead of covering it (spec `EDG-12`). It opens the closed
        // drawer and keeps dragging the open one back closed: once the panel is
        // on screen the strip is still part of the gesture, so a closing drag
        // does not have to start on the tab (`EDG-9`).
        //
        // Only composed when this drawer may act. A disabled `draggable` still
        // registers a pointer-input node in Compose and stays the topmost hit
        // route, which silently swallowed every tap meant for the *other*
        // drawer's backdrop (spec `EDG-22`). Skipping the node is the only
        // reliable way to take it out of hit-testing.
        val edgeStripIsOpen = isOpen || fraction > 0.01f
        if (edgeStripIsOpen || !otherDrawerOpen) {
            Box(
                modifier = Modifier
                    .align(topAlignment)
                    .padding(bottom = edgeStripBottomExclusion)
                    .fillMaxHeight()
                    .width(edgeStripWidth)
                    .draggable(
                        state = dragState,
                        orientation = Orientation.Horizontal,
                        onDragStarted = { startDrag() },
                        onDragStopped = { snapAfterDrag(it) },
                    ),
            )
        }

        // Drag preview: translucent panel that follows the finger.
        if (dragging && fraction > 0.02f && fraction < 0.98f) {
            Box(
                modifier = Modifier
                    .align(horizontalAlignment)
                    .fillMaxHeight()
                    .width(drawerWidth)
                    .offset { IntOffset(offsetX.value.toInt(), 0) }
                    .background(SignAiTheme.colors.surface.copy(alpha = 0.94f)),
                contentAlignment = Alignment.Center,
            ) {
                SignAiText(
                    text = previewLabel.uppercase(),
                    style = SignAiTheme.typography.label,
                    color = SignAiTheme.colors.muted,
                    modifier = Modifier.padding(horizontal = SignAiSpacing.lg),
                )
            }
        }

        // Backdrop (spec `EDG-9`/`EDG-10`): a full-screen scrim with the
        // prototype's weighted gradient — opaque at the drawer's edge, fully
        // transparent at the far side. It is composed BEFORE the panel and the
        // handle so those two win every touch inside the drawer, and everything
        // else (the exposed strip on the opposite side, the opposite handle's
        // spot, any empty corner) closes the drawer on tap.
        //
        // A full-screen node is required, not a strip: the drawer is 88% of the
        // screen, and the opposite handle sits in the remaining 12% right where a
        // user naturally taps to dismiss, so a strip-only backdrop left a dead
        // zone where tapping did nothing.
        if (fraction > 0.01f) {
            val base = SignAiTheme.colors.scrim
            val screenW = with(density) { maxWidth.toPx() }
            // Where the panel's leading edge is, in px, and which way the
            // gradient fades (from that edge toward the far screen edge).
            val edgeX =
                if (side == DrawerSide.End) offsetX.value
                else widthPx + offsetX.value
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .graphicsLayer { alpha = fraction }
                    .drawBehind {
                        val start = edgeX.coerceIn(0f, screenW)
                        val brush =
                            if (side == DrawerSide.End) {
                                Brush.horizontalGradient(
                                    colorStops = arrayOf(
                                        0f to Color.Transparent,
                                        1f to base,
                                    ),
                                    startX = 0f,
                                    endX = start.coerceAtLeast(1f),
                                )
                            } else {
                                Brush.horizontalGradient(
                                    colorStops = arrayOf(
                                        0f to base,
                                        1f to Color.Transparent,
                                    ),
                                    startX = start,
                                    endX = screenW.coerceAtLeast(start + 1f),
                                )
                            }
                        drawRect(brush = brush)
                    }
                    .clickable(
                        interactionSource = remember { MutableInteractionSource() },
                        indication = null,
                    ) { onOpenChange(false) },
            )
        }

        // Panel shadow: the prototype's `.side-panel { box-shadow: 0 0 28px
        // rgba(0,0,0,.12) }`. `Modifier.shadow` renders as hard side bands on
        // this Android version, and a stepped fake blur bands visibly. So the
        // shadow is ONE smooth gradient clipped to the panel's rounded
        // silhouette expanded by `shadowPx`: the outer boundary of the halo is
        // that rounded rect, so it follows the corner while the panel (drawn on
        // top) hides the middle. Composed before the panel and riding the same
        // `offsetX`, so it tracks the panel exactly while it moves.
        val panelMovable = isOpen || fraction > 0.001f
        val shadowBase = SignAiTheme.colors.scrim
        Box(
            modifier = Modifier
                .align(horizontalAlignment)
                .fillMaxHeight()
                .width(drawerWidth)
                .offset { IntOffset(offsetX.value.toInt(), 0) }
                .graphicsLayer { alpha = fraction }
                .drawBehind {
                    val shadowPx = 22.dp.toPx()
                    val cornerPx = 27.dp.toPx()
                    val outer = RoundRect(
                        rect = Rect(
                            left = -shadowPx,
                            top = -shadowPx,
                            right = size.width + shadowPx,
                            bottom = size.height + shadowPx,
                        ),
                        cornerRadius = CornerRadius(cornerPx + shadowPx),
                    )
                    val clip = Path().apply { addRoundRect(outer) }
                    clipPath(clip) {
                        val span = size.width + 2 * shadowPx
                        val edge0 = shadowPx / span
                        val edge1 = (shadowPx + size.width) / span
                        drawRect(
                            brush = Brush.horizontalGradient(
                                colorStops = arrayOf(
                                    0f to Color.Transparent,
                                    edge0 to shadowBase.copy(alpha = 0.12f),
                                    edge1 to shadowBase.copy(alpha = 0.12f),
                                    1f to Color.Transparent,
                                ),
                                startX = -shadowPx,
                                endX = size.width + shadowPx,
                            ),
                        )
                    }
                },
        ) {
            Box(Modifier.fillMaxSize())
        }

        Box(
            modifier = Modifier
                .align(horizontalAlignment)
                .fillMaxHeight()
                .width(drawerWidth)
                .offset { IntOffset(offsetX.value.toInt(), 0) }
                .then(
                    if (panelMovable) {
                        Modifier.draggable(
                            state = dragState,
                            orientation = Orientation.Horizontal,
                            onDragStarted = { startDrag() },
                            onDragStopped = { snapAfterDrag(it) },
                        )
                    } else {
                        Modifier
                    },
                ),
        ) {
            Surface(
                color = SignAiTheme.colors.surface,
                shape = drawerShape,
                modifier = Modifier.fillMaxSize(),
            ) {
                drawerContent()
            }
        }

        // Aquí estaba la franja `drawerOverflow` (64 dp de `surface` colgando
        // fuera de cuadro): existía solo para tapar el hueco en el borde
        // mientras el spring rebotaba. Con ζ = 1 el panel nunca pasa del borde,
        // así que no hay hueco que tapar y se fue con el rebote (2026-11-03).
        // No la repongas sin volver a medir el borde: la franja era un dp FIJO y,
        // con el panel ancho (`min(maxWidth * 0.88, 350.dp)`), un rebote de 16 %
        // ya se le acercaba al límite.

        // Handle: edge tab that rides the drawer's leading edge, matching the
        // prototype `.edge-tab` (globals.css): a small `surface` tab hugging the
        // screen edge, hairline `outline`, soft shadow and a two-line grip.
        // Tappable to open/close (spec `EDG-3`/`EDG-11`) and draggable. Composed
        // last so it stays tappable while the drawer is open.
        //
        // While the OTHER drawer is the active one this tab must not take any
        // touch — a pointer-input node is the topmost hit route in Compose even
        // when its gesture is disabled, and it used to swallow the active
        // drawer's backdrop taps (spec `EDG-22`). So instead of not composing it
        // (which made it vanish abruptly), it is always composed but the
        // `draggable`/`clickable` are attached only when it may act. A plain
        // layout node with no pointer input is skipped by hit-testing, and its
        // alpha rides `enabledFraction`, so it fades out gradually while the
        // counterpart opens.
        val tabShape =
            if (side == DrawerSide.End) SignAiShapes.cornerEdgeTabRight
            else SignAiShapes.cornerEdgeTabLeft
        // Interactive only while the counterpart is completely at rest. The
        // moment the other drawer starts moving (its fraction leaves 0) this tab
        // stops taking input, so two fingers cannot open both drawers at once
        // even though the fading tab is still visible (spec `EDG-19`/`EDG-22`).
        val handleEnabled = isOpen || (!otherDrawerOpen && otherOpenFraction <= 0.001f)
        Box(
            modifier = Modifier
                .align(horizontalAlignment)
                .offset {
                    val handleOffset =
                        if (side == DrawerSide.End) {
                            (offsetX.value - widthPx).coerceAtMost(0f)
                        } else {
                            (offsetX.value + widthPx).coerceAtLeast(0f)
                        }
                    IntOffset(
                        handleOffset.toInt(),
                        tabOffsetY.roundToPx(),
                    )
                }
                // La zona táctil es más ancha que el dibujo: el tab se sigue
                // dibujando con `contentAlignment` pegado al borde y el ancho extra
                // queda hacia adentro de la pantalla (ver [handleHitPadding]).
                .width((if (isOpen) handleDragWidth else edgeStripWidth) + handleHitPadding)
                // 200dp de alto (de 160) = +25 %, y además es **el máximo** que
                // Android deja excluir de los gestos del sistema por borde: pedir más
                // hace que ignore la exclusión.
                .height(200.dp)
                // Con navegación por gestos por el sistema, arrastrar desde el borde
                // de la pantalla no abre el panel: el gesto de "atrás" de Android se
                // queda con el touch antes de que llegue a la app (owner, 2026-10-22).
                // `systemGestureExclusion` le pide al sistema que no trate esta zona
                // como gesto de navegación, así el arrastre llega al `draggable` de
                // abajo. Es una **petición**: Android honra hasta 200dp por borde
                // (este nodo mide exactamente eso) y el fabricante puede tener su
                // propio criterio — en MIUI se verifica en el dispositivo.
                .systemGestureExclusion()
                .graphicsLayer { alpha = enabledFraction }
                .then(
                    if (handleEnabled) {
                        Modifier
                            .draggable(
                                state = dragState,
                                orientation = Orientation.Horizontal,
                                onDragStarted = { startDrag() },
                                onDragStopped = { snapAfterDrag(it) },
                            )
                            .pointerInput(isOpen, otherDrawerOpen) {
                                detectTapGestures(
                                    onPress = {
                                        // Claim on the first pointer event, so a
                                        // second finger on the other tab is
                                        // rejected in the same frame (`EDG-19`).
                                        gestureOwned = claimGesture()
                                        tryAwaitRelease()
                                        // No tap and no drag consumed it (the
                                        // gesture was cancelled): drop the lock.
                                        if (gestureOwned && !dragging) {
                                            gestureOwned = false
                                            releaseGesture()
                                        }
                                    },
                                    onTap = {
                                        if (gestureOwned) {
                                            gestureOwned = false
                                            releaseGesture()
                                            onOpenChange(!isOpen)
                                        }
                                    },
                                )
                            }
                            .semantics {
                                contentDescription =
                                    if (isOpen) "Cerrar panel" else "Abrir $previewLabel"
                            }
                    } else {
                        Modifier
                    },
                ),
            contentAlignment = if (side == DrawerSide.End) Alignment.CenterEnd else Alignment.CenterStart,
        ) {
            Box(
                modifier = Modifier
                    .width(20.dp)
                    .height(62.dp)
                    .shadow(elevation = 6.dp, shape = tabShape, clip = false)
                    .background(color = SignAiTheme.colors.surface, shape = tabShape)
                    .border(width = 1.dp, color = SignAiTheme.colors.outline, shape = tabShape),
                contentAlignment = Alignment.Center,
            ) {
                // Grip: two rounded vertical lines (prototype `.edge-grip`,
                // `box-shadow: 7px 0 0` → 4dp line + 3dp gap + 4dp line).
                Row(horizontalArrangement = Arrangement.spacedBy(3.dp)) {
                    repeat(2) {
                        Box(
                            modifier = Modifier
                                .width(4.dp)
                                .height(28.dp)
                                .background(
                                    color = SignAiTheme.colors.muted.copy(alpha = 0.65f),
                                    shape = SignAiShapes.cornerPill,
                                ),
                        )
                    }
                }
                // This handle belongs to the open drawer (the drawers nest, so
                // the opposite backdrop cannot reach it): it gets a mild dim
                // instead of vanishing behind the backdrop (spec `EDG-14`).
                val dim = SignAiTheme.colors.scrim.alpha * 0.5f * currentlyOpenFraction
                if (dim > 0f) {
                    Box(
                        modifier = Modifier
                            .matchParentSize()
                            .background(
                                color = SignAiTheme.colors.scrim.copy(alpha = dim),
                                shape = tabShape,
                            ),
                    )
                }
            }
        }
    }
