// CUSTOMIZED — not generated by `lumo --add` (Lumo has no side drawer).
//
// Gesture model:
// - OPEN: an invisible edge strip (right side, full height except the
//   bottom exclusion) is draggable. A swipe starting ANYWHERE on the
//   right edge — not just on the handle — opens the drawer. The strip
//   sits above `content` (so it wins touches over the WebView) but below
//   scrim/drawer (so it never interferes once the drawer is open).
// - CLOSE: the drawer body itself is draggable (drag right), or tap the
//   scrim. Both share one `DraggableState` with the same mapping, and
//   only one of them is hittable at a time (the drawer is off-screen
//   when closed, the strip is fully covered when open), so there is no
//   gesture ambiguity.
// - The handle (pill) TRAVELS WITH THE DRAWER: it is offset by the same
//   `offsetX` as the body, so when closed it rests flush against the
//   screen's right edge and when open it stays attached to the drawer's
//   leading (left) edge. It also carries the shared drag state, so the
//   tab itself can open the drawer (closed) or close it (open) — no jump,
//   no leaving the tab stranded on the far side of the drawer.
//
// Drive model: a single `Animatable<Float>` (offsetX, px from the
// drawer's resting edge). The drawer's `offset { offsetX }` slides the
// body with the finger frame-by-frame; on release we snap to 0 (open)
// or widthPx (closed) depending on the midpoint, with a bouncy spring.
//
// Delta convention (verified on device, easy to get wrong): Compose's
// `Modifier.draggable(orientation = Horizontal)` reports positive deltas
// for finger movement to the right, negative to the left. To OPEN, the
// offset must DECREASE (widthPx → 0) while the finger moves LEFT
// (negative delta) — hence `offsetX.value + delta`.

@Composable
fun SignAiEdgeDrawer(
    isOpen: Boolean,
    onOpenChange: (Boolean) -> Unit,
    modifier: Modifier = Modifier,
    drawerWidth: Dp = 300.dp,
    drawerOverflow: Dp = 64.dp,
    edgeStripWidth: Dp = 48.dp,
    edgeStripBottomExclusion: Dp = 0.dp,
    drawerContent: @Composable () -> Unit,
    content: @Composable () -> Unit,
) {
    val density = LocalDensity.current
    val widthPx = with(density) { drawerWidth.toPx() }
    val overflowPx = with(density) { drawerOverflow.toPx() }
    val scope = rememberCoroutineScope()
    val offsetX = remember { Animatable(if (isOpen) 0f else widthPx) }

    LaunchedEffect(isOpen) {
        offsetX.animateTo(
            targetValue = if (isOpen) 0f else widthPx,
            animationSpec = spring(
                dampingRatio = Spring.DampingRatioMediumBouncy,
                stiffness = Spring.StiffnessMedium,
            ),
        )
    }

    val fraction = ((widthPx - offsetX.value) / widthPx).coerceIn(0f, 1f)

    val dragState = rememberDraggableState { delta ->
        scope.launch {
            offsetX.snapTo((offsetX.value + delta).coerceIn(0f, widthPx))
        }
    }
    val snapAfterDrag: () -> Unit = {
        scope.launch {
            val shouldOpen = offsetX.value < widthPx / 2f
            offsetX.animateTo(
                targetValue = if (shouldOpen) 0f else widthPx,
                animationSpec = spring(
                    dampingRatio = Spring.DampingRatioMediumBouncy,
                    stiffness = Spring.StiffnessHigh,
                ),
            )
            onOpenChange(shouldOpen)
        }
    }

    Box(modifier = modifier.fillMaxSize()) {
        content()

        // Invisible open-gesture strip. `padding` BEFORE `fillMaxHeight`
        // shrinks the node itself, so the hit area excludes the bottom
        // bar (measured in MainScreen) instead of covering it.
        Box(
            modifier = Modifier
                .align(Alignment.TopEnd)
                .padding(bottom = edgeStripBottomExclusion)
                .fillMaxHeight()
                .width(edgeStripWidth)
                .draggable(
                    state = dragState,
                    orientation = Orientation.Horizontal,
                    onDragStopped = { snapAfterDrag() },
                ),
        )

        if (fraction > 0.01f) {
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .graphicsLayer { alpha = fraction * 0.5f }
                    .clickable(
                        interactionSource = remember { MutableInteractionSource() },
                        indication = null,
                    ) { onOpenChange(false) },
            )
        }

        // The body is `drawerOverflow` wider than the visible drawer and sits
        // shifted right by the same amount, so the extra surface hangs off the
        // screen's right edge (invisible at rest). On the open spring's rebound
        // the offset goes negative and the body slides left; without this extra
        // surface the body's right edge would separate from the screen edge and
        // expose the content behind. The visible drawer stays `drawerWidth`.
        Box(
            modifier = Modifier
                .align(Alignment.CenterEnd)
                .fillMaxHeight()
                .width(drawerWidth + drawerOverflow)
                .offset { IntOffset((offsetX.value + overflowPx).toInt(), 0) }
                .draggable(
                    state = dragState,
                    orientation = Orientation.Horizontal,
                    onDragStopped = { snapAfterDrag() },
                ),
        ) {
            Surface(
                color = SignAiTheme.colors.bar,
                modifier = Modifier
                    .align(Alignment.CenterStart)
                    .fillMaxHeight()
                    .width(drawerWidth),
            ) {
                drawerContent()
            }
            Box(
                modifier = Modifier
                    .align(Alignment.CenterEnd)
                    .fillMaxHeight()
                    .width(drawerOverflow)
                    .background(SignAiTheme.colors.bar),
            )
        }

        // Handle: grab tab that rides the drawer's leading edge. The
        // `- widthPx` term cancels the body's resting off-screen position,
        // so closed → flush with the screen edge; open → attached to the
        // sidebar's left edge. `coerceAtMost(0f)` keeps it from sliding
        // past the edge when the closing spring overshoots. Draggable so
        // it can both open and close.
        Box(
            modifier = Modifier
                .align(Alignment.CenterEnd)
                .offset { IntOffset((offsetX.value - widthPx).coerceAtMost(0f).toInt(), 0) }
                .width(edgeStripWidth)
                .height(160.dp)
                .draggable(
                    state = dragState,
                    orientation = Orientation.Horizontal,
                    onDragStopped = { snapAfterDrag() },
                ),
        ) {
            Box(
                modifier = Modifier
                    .align(Alignment.CenterEnd)
                    .width(5.dp)
                    .height(50.dp)
                    .shadow(
                        elevation = 2.dp,
                        shape = RoundedCornerShape(2.5.dp),
                    )
                    .background(
                        color = SignAiTheme.colors.primary.copy(alpha = 0.85f),
                        shape = RoundedCornerShape(2.5.dp),
                    ),
            )
        }
    }
}
