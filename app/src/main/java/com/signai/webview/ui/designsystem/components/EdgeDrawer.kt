// CUSTOMIZED — not generated by `lumo --add` (Lumo has no side drawer).
//
// Generalized to BOTH sides (spec `EDG-13`): `side = DrawerSide.Start` (left,
// Conversación) or `DrawerSide.End` (right, Ajustes). One gesture model:
//
// - OPEN: an invisible edge strip on the drawer's half of the screen is
//   draggable, plus a visible grab tab (handle) that can be tapped or dragged.
// - CLOSE: drag the body/handle toward the edge, or tap the scrim.
// - PREVIEW: while dragging, a translucent panel with the drawer label follows
//   the finger (spec `EDG-6`).
//
// Drive model: a single signed `Animatable<Float>` `offsetX` (px). Closed is at
// `direction * widthPx` (direction = +1 End / -1 Start), open is 0. Deltas are
// always `offsetX + delta` because opening is leftward on End and rightward on
// Start (Compose reports positive deltas for rightward finger movement).

enum class DrawerSide { Start, End }

@Composable
fun SignAiEdgeDrawer(
    side: DrawerSide,
    isOpen: Boolean,
    onOpenChange: (Boolean) -> Unit,
    modifier: Modifier = Modifier,
    drawerWidth: Dp = SignAiSizes.drawerWidth,
    drawerOverflow: Dp = 64.dp,
    edgeStripWidth: Dp = 48.dp,
    edgeStripBottomExclusion: Dp = 0.dp,
    previewLabel: String = "",
    drawerContent: @Composable () -> Unit,
    content: @Composable () -> Unit,
) {
    val density = LocalDensity.current
    val widthPx = with(density) { drawerWidth.toPx() }
    val overflowPx = with(density) { drawerOverflow.toPx() }
    val scope = rememberCoroutineScope()

    val direction = if (side == DrawerSide.End) 1f else -1f
    val closedOffset = direction * widthPx
    val minOffset = if (side == DrawerSide.End) 0f else -widthPx
    val maxOffset = if (side == DrawerSide.End) widthPx else 0f

    val offsetX = remember(side) { Animatable(if (isOpen) 0f else closedOffset) }
    var dragging by remember { mutableStateOf(false) }
    val reduceMotion = LocalReduceMotion.current

    LaunchedEffect(isOpen) {
        if (!dragging) {
            val target = if (isOpen) 0f else closedOffset
            if (reduceMotion) {
                offsetX.snapTo(target)
            } else {
                offsetX.animateTo(
                    targetValue = target,
                    animationSpec = spring(
                        dampingRatio = Spring.DampingRatioMediumBouncy,
                        stiffness = Spring.StiffnessMedium,
                    ),
                )
            }
        }
    }

    val fraction = (1f - abs(offsetX.value) / widthPx).coerceIn(0f, 1f)

    val dragState = rememberDraggableState { delta ->
        scope.launch {
            offsetX.snapTo((offsetX.value + delta).coerceIn(minOffset, maxOffset))
        }
    }
    val snapAfterDrag: () -> Unit = {
        scope.launch {
            dragging = false
            val shouldOpen = abs(offsetX.value) < widthPx / 2f
            val target = if (shouldOpen) 0f else closedOffset
            if (reduceMotion) {
                offsetX.snapTo(target)
            } else {
                offsetX.animateTo(
                    targetValue = target,
                    animationSpec = spring(
                        dampingRatio = Spring.DampingRatioMediumBouncy,
                        stiffness = Spring.StiffnessHigh,
                    ),
                )
            }
            onOpenChange(shouldOpen)
        }
    }

    val horizontalAlignment = if (side == DrawerSide.End) Alignment.CenterEnd else Alignment.CenterStart
    val topAlignment = if (side == DrawerSide.End) Alignment.TopEnd else Alignment.TopStart
    val dragDirectionSign = if (side == DrawerSide.End) 1f else -1f
    val drawerShape =
        if (side == DrawerSide.End) SignAiShapes.cornerDrawerRight
        else SignAiShapes.cornerDrawerLeft

    BoxWithConstraints(modifier = modifier.fillMaxSize()) {
        content()

        // Prototype `.edge-tab { top: 42% }`: the tab's top sits at 42% of the
        // screen height, i.e. slightly above the vertical center. The handle Box
        // is 160dp tall and centered, so shift it up by 8% of the height (plus
        // the half-tab correction to align the 62dp tab's top).
        val tabOffsetY = 31.dp - maxHeight * 0.08f

        // Invisible open-gesture strip on this drawer's edge. `padding` BEFORE
        // `fillMaxHeight` shrinks the node itself, so the hit area excludes the
        // bottom bar instead of covering it (spec `EDG-12`).
        Box(
            modifier = Modifier
                .align(topAlignment)
                .padding(bottom = edgeStripBottomExclusion)
                .fillMaxHeight()
                .width(edgeStripWidth)
                .draggable(
                    state = dragState,
                    orientation = Orientation.Horizontal,
                    onDragStarted = { dragging = true },
                    onDragStopped = { snapAfterDrag() },
                ),
        )

        if (fraction > 0.01f) {
            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .graphicsLayer { alpha = fraction * 0.28f }
                    .background(Color.Black)
                    .clickable(
                        interactionSource = remember { MutableInteractionSource() },
                        indication = null,
                    ) { onOpenChange(false) },
            )
        }

        // Drag preview: translucent panel that follows the finger.
        if (dragging && fraction > 0.02f && fraction < 0.98f) {
            Box(
                modifier = Modifier
                    .align(horizontalAlignment)
                    .fillMaxHeight()
                    .width(drawerWidth)
                    .offset { IntOffset(offsetX.value.toInt(), 0) }
                    .background(SignAiTheme.colors.surface.copy(alpha = 0.94f)),
                contentAlignment = Alignment.Center,
            ) {
                SignAiText(
                    text = previewLabel.uppercase(),
                    style = SignAiTheme.typography.label,
                    color = SignAiTheme.colors.muted,
                    modifier = Modifier.padding(horizontal = SignAiSpacing.lg),
                )
            }
        }

        // Drawer surface: exactly `drawerWidth`, aligned to its edge and riding
        // `offsetX`. Kept at its natural size (not wider than the parent) because
        // a body wider than the Box gets centered instead of edge-aligned, which
        // opened a gap between the drawer and its handle.
        Box(
            modifier = Modifier
                .align(horizontalAlignment)
                .fillMaxHeight()
                .width(drawerWidth)
                .offset { IntOffset(offsetX.value.toInt(), 0) }
                .draggable(
                    state = dragState,
                    orientation = Orientation.Horizontal,
                    onDragStarted = { dragging = true },
                    onDragStopped = { snapAfterDrag() },
                ),
        ) {
            Surface(
                color = SignAiTheme.colors.surface,
                shape = drawerShape,
                modifier = Modifier.fillMaxSize(),
            ) {
                drawerContent()
            }
        }

        // Overflow strip: an extra `drawerOverflow` of surface hanging off the
        // trailing screen edge. On the open spring's rebound `offsetX` overshoots
        // past 0; this keeps the edge covered instead of exposing the content
        // behind. Invisible at rest.
        Box(
            modifier = Modifier
                .align(horizontalAlignment)
                .fillMaxHeight()
                .width(drawerOverflow)
                .offset { IntOffset((offsetX.value + dragDirectionSign * overflowPx).toInt(), 0) }
                .background(SignAiTheme.colors.surface),
        )

        // Handle: edge tab that rides the drawer's leading edge, matching the
        // prototype `.edge-tab` (globals.css): a small `surface` tab hugging the
        // screen edge, hairline `outline`, soft shadow and a two-line grip.
        // Tappable to open/close (spec `EDG-3`/`EDG-11`) and draggable.
        val tabShape =
            if (side == DrawerSide.End) SignAiShapes.cornerEdgeTabRight
            else SignAiShapes.cornerEdgeTabLeft
        Box(
            modifier = Modifier
                .align(horizontalAlignment)
                .offset {
                    val handleOffset =
                        if (side == DrawerSide.End) {
                            (offsetX.value - widthPx).coerceAtMost(0f)
                        } else {
                            (offsetX.value + widthPx).coerceAtLeast(0f)
                        }
                    IntOffset(handleOffset.toInt(), tabOffsetY.roundToPx())
                }
                .width(edgeStripWidth)
                .height(160.dp)
                .draggable(
                    state = dragState,
                    orientation = Orientation.Horizontal,
                    onDragStarted = { dragging = true },
                    onDragStopped = { snapAfterDrag() },
                )
                .clickable { onOpenChange(!isOpen) }
                .semantics {
                    contentDescription = if (isOpen) "Cerrar panel" else "Abrir $previewLabel"
                },
            contentAlignment = if (side == DrawerSide.End) Alignment.CenterEnd else Alignment.CenterStart,
        ) {
            Box(
                modifier = Modifier
                    .width(20.dp)
                    .height(62.dp)
                    .shadow(elevation = 6.dp, shape = tabShape, clip = false)
                    .background(color = SignAiTheme.colors.surface, shape = tabShape)
                    .border(width = 1.dp, color = SignAiTheme.colors.outline, shape = tabShape),
                contentAlignment = Alignment.Center,
            ) {
                // Grip: two rounded vertical lines (prototype `.edge-grip`,
                // `box-shadow: 7px 0 0` → 4dp line + 3dp gap + 4dp line).
                Row(horizontalArrangement = Arrangement.spacedBy(3.dp)) {
                    repeat(2) {
                        Box(
                            modifier = Modifier
                                .width(4.dp)
                                .height(28.dp)
                                .background(
                                    color = SignAiTheme.colors.muted.copy(alpha = 0.65f),
                                    shape = SignAiShapes.cornerPill,
                                ),
                        )
                    }
                }
            }
        }
    }
}
